export const getWindColor = (speed: number) => {
  if (speed < 10) return 'text-white/60';
  if (speed < 15) return 'text-cyan-400';
  if (speed < 22) return 'text-teal-400';
  if (speed < 30) return 'text-orange-400';
  return 'text-rose-500';
};

export const getWindBg = (speed: number) => {
  if (speed < 10) return 'bg-white/5';
  if (speed < 15) return 'bg-cyan-500/10';
  if (speed < 22) return 'bg-teal-500/10';
  if (speed < 30) return 'bg-orange-500/10';
  return 'bg-rose-500/10';
};

export const getWeatherDesc = (code: number) => {
  if (code === 0) return 'Céu Limpo';
  if (code <= 3) return 'Parcialmente Nublado';
  if (code <= 48) return 'Nevoeiro';
  if (code <= 67) return 'Chuva Leve';
  return 'Chuva';
};

