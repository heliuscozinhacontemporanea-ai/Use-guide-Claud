export type BookingErrorCode =
  | 'VALIDATION_ERROR'
  | 'FORBIDDEN'
  | 'EMAIL_NOT_VERIFIED'
  | 'NOT_FOUND'
  | 'SLOT_UNAVAILABLE'
  | 'INSUFFICIENT_CAPACITY'
  | 'INVALID_TRANSITION'
  | 'LATE_PAYMENT_REJECTED'
  | 'KIND_NOT_AVAILABLE'
  | 'CANCELLATION_NOT_ALLOWED'
  | 'PARTNER_SUSPENDED'
  | 'POLICY_CHANGE_NOT_ALLOWED'
  | 'TERMS_NOT_ACCEPTED'
  | 'SERVICE_UNAVAILABLE'
  | 'CHECK_IN_NOT_APPLICABLE'
  | 'CHECK_IN_WINDOW_CLOSED'
  | 'INVALID_CHECK_IN_CODE'
  | 'CHECK_IN_LOCKED'
  | 'NO_SHOW_TOO_EARLY'
  | 'ABSENCE_REPORT_NOT_ALLOWED'
  | 'NOTHING_TO_ANSWER';

const STATUS_BY_CODE: Record<BookingErrorCode, number> = {
  VALIDATION_ERROR: 400,
  FORBIDDEN: 403,
  EMAIL_NOT_VERIFIED: 403,
  NOT_FOUND: 404,
  SLOT_UNAVAILABLE: 409,
  INSUFFICIENT_CAPACITY: 409,
  INVALID_TRANSITION: 409,
  LATE_PAYMENT_REJECTED: 409,
  KIND_NOT_AVAILABLE: 422,
  CANCELLATION_NOT_ALLOWED: 422,
  PARTNER_SUSPENDED: 403,
  POLICY_CHANGE_NOT_ALLOWED: 422,
  TERMS_NOT_ACCEPTED: 422,
  SERVICE_UNAVAILABLE: 503,
  CHECK_IN_NOT_APPLICABLE: 422,
  CHECK_IN_WINDOW_CLOSED: 422,
  INVALID_CHECK_IN_CODE: 422,
  CHECK_IN_LOCKED: 429,
  NO_SHOW_TOO_EARLY: 422,
  ABSENCE_REPORT_NOT_ALLOWED: 422,
  NOTHING_TO_ANSWER: 409,
};

export class BookingDomainError extends Error {
  readonly statusCode: number;

  constructor(
    public readonly code: BookingErrorCode,
    message: string
  ) {
    super(message);
    this.name = 'BookingDomainError';
    this.statusCode = STATUS_BY_CODE[code];
  }
}
